#requires -Version 5.0
[CmdletBinding()]
param(
    # Optional. When omitted, every substrate directory under the evidence root that carries a
    # manifest is examined. This is a NAME the operator supplies, never a session_id and never an
    # inferred dispatch id -- this file reads no payload from which either could be taken.
    [string]$SubstrateName,

    [string]$RepositoryRootPath = (Split-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) -Parent),

    # Explicit or nothing is written. No default path, and never a path inside the evidence plane
    # chosen by this file.
    [string]$ResultPath
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$script:ManifestFileName = '00-substrate-manifest.json'
$script:RecordFileName = '00-placement-record.json'

function Write-Line { param([AllowEmptyString()][string]$Text) [Console]::Out.WriteLine($Text) }

function Get-FileSha256 {
    param([string]$Path)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $fs = [System.IO.File]::OpenRead($Path)
    try { return (($sha.ComputeHash($fs) | ForEach-Object { $_.ToString('x2') }) -join '') }
    finally { $fs.Dispose(); $sha.Dispose() }
}

function Write-Utf8NoBom {
    # Erratum #12: Set-Content -Encoding UTF8 emits a BOM under PS 5.1. Never used here.
    param([string]$Path, [string]$Text)
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($false)))
}

$evidenceRootPath = Join-Path (Join-Path $RepositoryRootPath '.mission') 'evidence'

Write-Line '=== evidence-verify-placement =================================================='
Write-Line 'WIRED TO NOTHING. Reads no hook payload and no stdin. Contract SS 9.2 retirement'
Write-Line 'condition 3 is OPEN, not satisfied -- the "if any" is not read as vacuous.'
Write-Line ("evidence root : {0}" -f $evidenceRootPath)

if (-not (Test-Path -LiteralPath $evidenceRootPath -PathType Container)) {
    Write-Line ''
    Write-Line 'OUTCOME: NOTHING VERIFIABLE -- the evidence root does not exist. No substrate was judged.'
    Write-Line 'EXIT: 2'
    exit 2
}

$candidatePaths = @()
if ($SubstrateName) {
    $one = Join-Path $evidenceRootPath $SubstrateName
    if (Test-Path -LiteralPath $one -PathType Container) { $candidatePaths = @($one) }
}
else {
    $candidatePaths = @(Get-ChildItem -LiteralPath $evidenceRootPath -Directory -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName })
}

$subjects = @($candidatePaths | Where-Object { Test-Path -LiteralPath (Join-Path $_ $script:ManifestFileName) -PathType Leaf })

if ($subjects.Count -eq 0) {
    Write-Line ''
    Write-Line 'OUTCOME: NOTHING VERIFIABLE -- no substrate under the evidence root carries a manifest.'
    Write-Line 'A substrate that was never staged leaves nothing to verify and is NOT reported here'
    Write-Line '(contract SS 11.2). No substrate was judged.'
    Write-Line 'EXIT: 2'
    exit 2
}

$results = @()
$mismatchCount = 0

foreach ($subjectPath in $subjects) {
    $name = Split-Path $subjectPath -Leaf
    Write-Line ''
    Write-Line ("--- {0} " -f $name).PadRight(80, '-')

    $findings = @()
    $manifestPath = Join-Path $subjectPath $script:ManifestFileName
    $manifest = $null
    try { $manifest = (Get-Content -LiteralPath $manifestPath -Raw) | ConvertFrom-Json }
    catch { $findings += ("manifest is not parseable JSON: {0}" -f $_.Exception.Message) }

    $manifestEntries = @()
    if ($manifest -and ($manifest.PSObject.Properties.Name -contains 'files')) { $manifestEntries = @($manifest.files) }
    else { $findings += "manifest has no 'files' member" }

    # The record's own destination digests, when a record is present. Absence is reported and is not
    # by itself a mismatch: a substrate placed by the ledger:1250 interim route carries no record.
    $recordPath = Join-Path $subjectPath $script:RecordFileName
    $recordDigests = @{}
    $recordPresent = Test-Path -LiteralPath $recordPath -PathType Leaf
    if ($recordPresent) {
        try {
            $record = (Get-Content -LiteralPath $recordPath -Raw) | ConvertFrom-Json
            if ($record.PSObject.Properties.Name -contains 'files') {
                foreach ($f in @($record.files)) { $recordDigests[[string]$f.name] = [string]$f.destination_sha256 }
            }
        }
        catch { $findings += ("placement record is not parseable JSON: {0}" -f $_.Exception.Message) }
    }
    else {
        Write-Line '  note: no placement record present (a substrate placed by the ledger:1250 interim'
        Write-Line '        operator-copy route carries none). Manifest agreement is still decided.'
    }

    $presentNames = @(Get-ChildItem -LiteralPath $subjectPath -File | ForEach-Object { $_.Name })
    $manifestNames = @($manifestEntries | ForEach-Object { [string]$_.name })
    $expectedExtra = @($script:ManifestFileName, $script:RecordFileName)

    foreach ($n in $manifestNames) {
        if ($presentNames -notcontains $n) { $findings += ("manifest names '{0}' but it is absent at the destination" -f $n) }
    }
    foreach ($n in $presentNames) {
        if ($expectedExtra -contains $n) { continue }
        if ($manifestNames -notcontains $n) { $findings += ("'{0}' is present at the destination but the manifest does not name it" -f $n) }
    }

    foreach ($e in $manifestEntries) {
        $n = [string]$e.name
        $p = Join-Path $subjectPath $n
        if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { continue }
        $sha = Get-FileSha256 -Path $p
        $bytes = (Get-Item -LiteralPath $p).Length
        $manifestSha = ([string]$e.sha256).ToLowerInvariant()
        $agreeManifest = ($sha -eq $manifestSha) -and ([int64]$bytes -eq [int64]$e.bytes)
        if (-not $agreeManifest) {
            $findings += ("'{0}': manifest {1} ({2} b), re-derived at destination {3} ({4} b)" -f $n, $manifestSha, [int64]$e.bytes, $sha, $bytes)
        }
        if ($recordDigests.ContainsKey($n) -and $recordDigests[$n] -ne $sha) {
            $findings += ("'{0}': placement record recorded destination {1}, re-derived now {2} -- drift AFTER placement" -f $n, $recordDigests[$n], $sha)
        }
        Write-Line ("  {0}  {1}  {2} b  {3}" -f $(if ($agreeManifest) { 'OK  ' } else { 'DIFF' }), $n, $bytes, $sha)
    }

    $verdict = 'VERIFIED'
    if ($findings.Count -gt 0) { $verdict = 'MISMATCH'; $mismatchCount++ }
    Write-Line ("  verdict: {0}" -f $verdict)
    foreach ($f in $findings) { Write-Line ("    - {0}" -f $f) }

    $results += [pscustomobject]@{
        substrate       = $name
        verdict         = $verdict
        record_present  = $recordPresent
        files_examined  = $manifestNames.Count
        findings        = $findings
    }
}

if ($ResultPath) {
    $payload = [pscustomobject]@{
        verify_result_version = 1
        wired                 = $false
        wiring_note           = 'This leg is BUILT AND NOT WIRED. Contract SS 9.2 retirement condition 3 is OPEN, not satisfied; the "if any" is not read as vacuous satisfaction.'
        evidence_root         = $evidenceRootPath
        substrates            = $results
    }
    $json = ConvertTo-Json -InputObject $payload -Depth 6
    Write-Utf8NoBom -Path $ResultPath -Text ((($json -replace "`r`n", "`n")) + "`n")
    Write-Line ''
    Write-Line ("result written: {0}" -f $ResultPath)
}

Write-Line ''
Write-Line ("OUTCOME: {0} substrate(s) examined, {1} MISMATCH" -f $results.Count, $mismatchCount)
if ($mismatchCount -gt 0) { Write-Line 'EXIT: 3'; exit 3 }
Write-Line 'EXIT: 0'
exit 0
